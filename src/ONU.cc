
#include <omnetpp.h>
#include <queue>
#include <algorithm>
#include <cmath>
#include <cstdint>
#include <fstream>
#include <string>

using namespace omnetpp;

class ONU : public cSimpleModule
{
  private:
    cMessage *generateMsg = nullptr;
    cMessage *transmitMsg = nullptr;
    cMessage *trafficStateMsg = nullptr;

    simtime_t currentReportTxStart;
    long currentReportedBytes = 0;
    bool awaitingGateForReport = false;
    std::ofstream reportTurnaroundFile;
    // Pareto ON/OFF traffic source. Values are read from ONU.ned.
    bool trafficOn = false;
    simtime_t onPacketInterval;
    double mon = 0.0;
    double moff = 0.0;
    double paretoA = 1e-12;
    double paretoB = 1.0;
    double alphaOn = 1.2;
    double alphaOff = 1.4;
    
    cPacket *pendingReport = nullptr;

    // DATA generated by this ONU.
    std::queue<cPacket *> queue;

    // Local Sharing packets are buffered separately so the Host forwards
    // all collected REPORTs before forwarding any collected DATA.
    std::queue<cPacket *> ReportBuffers;
    std::queue<cPacket *> DataBuffers;

    // Mode 2 sends the Host's own REPORT before its own DATA burst.
    bool hostReportSentBeforeData = false;

    // After the Host REPORT is sent, the Host is free to accept a new GATE
    // from the OLT, but must finish the previous Mode 2 continuation first.
    // Keep the arriving GATE intact until the previous Host work is complete.
    bool hostPostReportActive = false;
    cMessage *deferredGrant = nullptr;

    long grantBitsRemaining = 0;
    long long packetsCreated = 0;
    long long packetsDropped = 0;
    SimTime PDB ;
    SimTime oltToRNDelay;
    SimTime rnToONUDelay;
    SimTime DelayExperiencedByPacket;
    bool waitingToSendReport = false;
    bool grantActive = false;
    bool sendingLocalSharingBuffer = false;

    // Grant modes:
    // 0 = normal upstream
    // 1 = Local Sharing contributor
    // 2 = Local Sharing Host
    int grantMode = 0;

    // Host selected for the current contributor grant.
    int grantHostId = -1;

  protected:
    virtual void initialize() override;
    virtual void handleMessage(cMessage *msg) override;
    virtual void finish() override;

    void receiveLocalSharingPacket(cPacket *packet);
    void prepareReport(long reportedQueueBytes = -1);
    void dropExpiredOwnPackets();
    long calculateSendableOwnBytes(long availableGrantBits) const;
    long getQueuedBytes() const;
    void transmitNextLocalSharingPacket();
    void resumeDeferredGrant();
    simtime_t sampleParetoDuration(double scaleSeconds, double alpha);
};

Define_Module(ONU);


void ONU::initialize()
{
    cModule *network = getParentModule();

    generateMsg = new cMessage("Generate");
    transmitMsg = new cMessage("Transmit");
    trafficStateMsg = new cMessage("TrafficState");


    //Read packet dealay budget from ONU.ned
    PDB = par("PDB").doubleValue();
    oltToRNDelay = network->par("del_OLTtoRN"); 
    rnToONUDelay = par("rnToONUDelay");


    // Read the traffic parameters directly from ONU.ned.
    const double link = par("dataRate").doubleValue();
    const double packetBits = par("packetSize").intValue();
    const double load = par("load").doubleValue();
    const double pmin = 1.0;

    if (link <= 0.0)
        throw cRuntimeError("ONU dataRate must be positive");
    if (packetBits <= 0)
        throw cRuntimeError("ONU packetSize must be positive");
    if (load <= 0.0 || load >= 1.0)
        throw cRuntimeError("ONU load must be greater than 0 and less than 1");

    const double ton = (alphaOn - 1.0) / alphaOn;
    const double toff = (alphaOff - 1.0) / alphaOff;

    // Scale parameters from the original Pareto ON/OFF model, using this
    // ONU's configured packet size and data rate rather than fixed constants.
    mon = pmin * packetBits / link;
    moff = mon * (toff / ton) * (1.0 / load - 1.0);

    // Fixed packet spacing while ON: one configured packet's serialization time.
    onPacketInterval = SimTime(packetBits / link, SIMTIME_S);

    grantBitsRemaining = 0;
    waitingToSendReport = false;
    grantActive = false;
    sendingLocalSharingBuffer = false;

    grantMode = 0;
    grantHostId = -1;
    hostReportSentBeforeData = false;
    hostPostReportActive = false;
    deferredGrant = nullptr;

    EV_INFO << "ONU " << par("onuId").intValue()
            << " initialized"
            << " | load = " << load
            << " | packet size = " << packetBits << " bits"
            << " | data rate = " << link << " bps"
            << " | ON packet interval = " << onPacketInterval.dbl() << " s"
            << endl;

    // Start in an ON period. The first packet is generated at the start of ON.
    trafficOn = true;
    scheduleAt(simTime() + sampleParetoDuration(mon, alphaOn), trafficStateMsg);
    scheduleAt(simTime(), generateMsg);

    // Keep each ONU's measurements in a separate file; otherwise each ONU
    // opening the same filename could truncate another ONU's data.
    const std::string turnaroundFilename =
        "report_turnaround_ONU_" +
        std::to_string(par("onuId").intValue()) +
        ".csv";

    reportTurnaroundFile.open(turnaroundFilename);

    if (!reportTurnaroundFile.is_open())
        throw cRuntimeError("Cannot open %s", turnaroundFilename.c_str());

    reportTurnaroundFile
        << "onuId,reportedBytes,reportTxStart_s,gateArrival_s,turnAroundTime_s\n";
}


simtime_t ONU::sampleParetoDuration(double scaleSeconds, double alpha)
{
    // Original Pareto sampling equation.
    double u = uniform(paretoA, paretoB);

    if (u <= 0.0)
        u = paretoA;

    const double durationSeconds =
        scaleSeconds / pow(u, 1.0 / alpha);

    // Quantize the duration to the 1 ps simulation-time resolution.
    constexpr double TICKS_PER_SECOND = 1e12;

    const int64_t ticks = static_cast<int64_t>(
        std::llround(durationSeconds * TICKS_PER_SECOND)
    );

    return SimTime(ticks, SIMTIME_PS);
}

long ONU::getQueuedBytes() const
{
    long bytes = 0;
    std::queue<cPacket *> temp = queue;

    while (!temp.empty())
    {
        bytes += temp.front()->getBitLength() / 8;
        temp.pop();
    }

    return bytes;
}


// Receive packets reflected by the Splitter.
// The packet's hostId determines which ONU retains it.
void ONU::receiveLocalSharingPacket(cPacket *packet)
{
    int myId = par("onuId").intValue();

    if (!packet->hasPar("hostId"))
    {
        EV_WARN << "ONU " << myId
                << " discarding Local Sharing packet without hostId"
                << endl;

        delete packet;
        return;
    }

    int packetHostId =
        (int)packet->par("hostId").longValue();

    // This copy is intended for another Host.
    if (packetHostId != myId)
    {
        // EV_INFO << "ONU " << myId
        //         << " discarding reflected packet"
        //         << " | Packet type = " << packet->getName()
        //         << " | Intended Host = " << packetHostId
        //         << endl;

        delete packet;
        return;
    }

    // Only DATA and REPORT are forwarded by Local Sharing.
    if (!packet->isName("DATA") &&
        !packet->isName("REPORT"))
    {
        EV_WARN << "ONU " << myId
                << " discarding unsupported Local Sharing packet "
                << packet->getName()
                << endl;

        delete packet;
        return;
    }

    EV_INFO << "ONU " << myId
            << " collected Local Sharing packet"
            << " | Type = " << packet->getName();

    if (packet->hasPar("onuId"))
    {
        EV_INFO << " | Original source ONU = "
                << packet->par("onuId").longValue();
    }

    if (packet->isName("REPORT") &&
        packet->hasPar("queueBytes"))
    {
        EV_INFO << " | Reported queue = "
                << packet->par("queueBytes").longValue()
                << " bytes";
    }

    // Keep REPORTs and DATA separate: REPORTs have upstream priority.
    if (packet->isName("REPORT"))
        ReportBuffers.push(packet);
    else
        DataBuffers.push(packet);

    EV_INFO << " | Buffered REPORTs = " << ReportBuffers.size()
            << " | Buffered DATA = " << DataBuffers.size()
            << endl;
}


// Prepare a separate REPORT using this ONU's own queue.
// The REPORT's hostId is initially -1.
// In Mode 1, it is set to grantHostId immediately before sending.
void ONU::prepareReport(long reportedQueueBytes)
{
    if (pendingReport != nullptr)
    {
        throw cRuntimeError("A REPORT is already pending");
    }

    pendingReport = new cPacket("REPORT");

    long reportBits =
        par("reportSizeBytes").intValue() * 8L;

    pendingReport->setBitLength(reportBits);

    pendingReport->addPar("onuId");
    pendingReport->par("onuId").setLongValue(
        (long)par("onuId").intValue()
    );

    pendingReport->addPar("queueBytes");
    // For a Mode 2 Host, this is the predicted queue after its current
    // grant's sendable DATA packets have been transmitted.
    const long queueBytesToReport =
        (reportedQueueBytes >= 0) ? reportedQueueBytes : getQueuedBytes();

    pendingReport->par("queueBytes").setLongValue(queueBytesToReport);

    pendingReport->addPar("hostId");
    pendingReport->par("hostId").setLongValue(-1);

    waitingToSendReport = true;

    SimTime reportTxTime(
        reportBits / par("dataRate").doubleValue(),
        SIMTIME_S
    );

    // EV_INFO << "ONU " << par("onuId").intValue()
    //         << " preparing REPORT"
    //         << " | Queue bytes = "
    //         << pendingReport->par("queueBytes").longValue()
    //         << " | Grant mode = " << grantMode
    //         << " | Duration = "
    //         << reportTxTime.dbl() * 1e9 << " ns"
    //         << endl;

    scheduleAt(simTime() + reportTxTime, transmitMsg);
}


// Forward Local Sharing packets in strict priority order:
// all collected REPORTs first, then all collected DATA.
void ONU::transmitNextLocalSharingPacket()
{
    cPacket *packet = nullptr;

    if (!ReportBuffers.empty())
    {
        packet = ReportBuffers.front();
        ReportBuffers.pop();
    }
    else if (!DataBuffers.empty())
    {
        packet = DataBuffers.front();
        DataBuffers.pop();
    }
    else
    {
        throw cRuntimeError(
            "Cannot transmit: both Local Sharing buffers are empty"
        );
    }

    // Locally shared REPORTs and DATA are forwarded independently of the
    // Host's own upstream grant. Neither packet type changes grantBitsRemaining.

    SimTime txTime(
        packet->getBitLength() /
        par("dataRate").doubleValue(),
        SIMTIME_S
    );

    EV_INFO << "Host ONU " << par("onuId").intValue()
            << " forwarding Local Sharing packet"
            << " | Type = " << packet->getName();

    if (packet->hasPar("onuId"))
    {
        EV_INFO << " | Original source ONU = "
                << packet->par("onuId").longValue();
    }

    EV_INFO << " | Host ID = "
            << packet->par("hostId").longValue()
            << " | Bits = " << packet->getBitLength()
            << " | REPORTs remaining = " << ReportBuffers.size()
            << " | DATA remaining = " << DataBuffers.size()
            << endl;

    packet->setKind(2);
    send(packet, "out");

    // The next event continues REPORT draining before DATA draining.
    scheduleAt(simTime() + txTime, transmitMsg);
}


// Resume a GATE that arrived while the Host was finishing the previous
// Mode 2 post-REPORT work. Its original requested start time is preserved.
void ONU::resumeDeferredGrant()
{
    if (deferredGrant == nullptr)
        return;

    const SimTime readyAt =
        SimTime(deferredGrant->par("deferredReadyAt").doubleValue(), SIMTIME_S);

    // The stored GATE's delay_after_rec_grant is set to zero when deferred,
    // because its original delay is represented by deferredReadyAt.
    const SimTime resumeAt = std::max(simTime(), readyAt);

    cMessage *grant = deferredGrant;
    deferredGrant = nullptr;

    EV_INFO << "ONU " << par("onuId").intValue()
            << " resuming deferred GATE"
            << " | Original ready time = " << readyAt
            << " | Resume time = " << resumeAt
            << endl;

    scheduleAt(resumeAt, grant);
}


// Drop expired packets from this ONU's own DATA queue before preparing
// the Host's pre-DATA REPORT.
void ONU::dropExpiredOwnPackets()
{
    const SimTime allowedDelay = PDB - rnToONUDelay - oltToRNDelay;

    while (!queue.empty())
    {
        cPacket *packet = queue.front();
        const SimTime packetAge = simTime() - packet->getCreationTime();

        if (packetAge <= allowedDelay)
            break;

        queue.pop();
        packetsDropped++;
        delete packet;
    }
}


// Calculate the bytes sendable from the current own queue under the
// remaining grant, without removing packets from the queue yet.
long ONU::calculateSendableOwnBytes(long availableGrantBits) const
{
    long bitsRemaining = availableGrantBits;
    long sendableBytes = 0;
    std::queue<cPacket *> temp = queue;

    while (!temp.empty())
    {
        cPacket *packet = temp.front();
        const long packetBits = packet->getBitLength();

        if (packetBits > bitsRemaining)
            break;

        bitsRemaining -= packetBits;
        sendableBytes += packetBits / 8;
        temp.pop();
    }

    return sendableBytes;
}

void ONU::handleMessage(cMessage *msg)
{
    // ========================================
    // PACKET GENERATION
    // ========================================

    if (msg == trafficStateMsg)
    {
        if (trafficOn)
        {
            // ON -> OFF: stop packet generation and schedule the OFF duration.
            trafficOn = false;
            if (generateMsg->isScheduled())
                cancelEvent(generateMsg);

            scheduleAt(simTime() + sampleParetoDuration(moff, alphaOff),
                trafficStateMsg);
        }
        else
        {
            // OFF -> ON: schedule the next ON duration and resume packet arrivals.
            trafficOn = true;
            scheduleAt(simTime() + sampleParetoDuration(mon, alphaOn),
                trafficStateMsg);
            scheduleAt(simTime(), generateMsg);
        }
        return;
    }

    if (msg == generateMsg)
    {
        if (!trafficOn)
            return;

        cPacket *packet = new cPacket("DATA");

        packet->setBitLength(
            par("packetSize").intValue()
        );

        packet->addPar("onuId");
        packet->par("onuId").setLongValue(
            (long)par("onuId").intValue()
        );

        // Retain the existing destination marker.
        // 1 = HOST, 2 = OLT.
        packet->addPar("destination");
        packet->par("destination").setLongValue(2);

        // No Host has been assigned until a Mode 1 grant is used.
        packet->addPar("hostId");
        packet->par("hostId").setLongValue(-1);

        queue.push(packet);
        packetsCreated++;
        // EV_INFO << "ONU " << par("onuId").intValue()
        //         << " generated DATA"
        //         << " | Queue packets = " << queue.size()
        //         << endl;

        // Constant spacing while ON, derived from packetSize / dataRate.
        scheduleAt(simTime() + onPacketInterval, generateMsg);

        return;
    }


    // ========================================
    // LOCAL SHARING PACKET RECEPTION
    // ========================================

    if (msg->getArrivalGate() != nullptr &&
        msg->getArrivalGate()->isName("lsIn"))
    {
        cPacket *packet = check_and_cast<cPacket *>(msg);
        receiveLocalSharingPacket(packet);
        return;
    }


    // ========================================
    // BROADCAST GATE RECEPTION
    // ========================================

    if (msg->isName("Grant"))
    {
        int destinationONU =
            (int)msg->par("onuId").longValue();

        // The Splitter broadcasts every GATE.
        // Only the addressed ONU processes it.
        if (destinationONU != par("onuId").intValue())
        {
            delete msg;
            return;
        }

        // Record the first GATE addressed to this ONU after REPORT transmission.
        if (awaitingGateForReport)
        {
            const simtime_t gateArrival = simTime();
            const simtime_t turnAroundTime =
                gateArrival - currentReportTxStart;

            reportTurnaroundFile
                << par("onuId").intValue() << ","
                << currentReportedBytes << ","
                << currentReportTxStart.dbl() << ","
                << gateArrival.dbl() << ","
                << turnAroundTime.dbl() << "\n";
            reportTurnaroundFile.flush();

            EV_INFO << "ONU " << par("onuId").intValue()
                    << " REPORT-to-GATE turnaround"
                    << " | Reported bytes = " << currentReportedBytes
                    << " | REPORT TX start = " << currentReportTxStart
                    << " | GATE arrival = " << gateArrival
                    << " | Turnaround = " << turnAroundTime
                    << endl;

            awaitingGateForReport = false;
        }

        int mode = (int)msg->par("mode").longValue();
        int hostId = (int)msg->par("hostId").longValue();

        double lsDuration =
            msg->par("lsDuration").doubleValue();

        if (mode < 0 || mode > 2)
        {
            delete msg;
            throw cRuntimeError("Invalid Grant mode");
        }

        int numONUs =
            getParentModule()->par("numONUs").intValue();

        // Only Mode 1 requires a valid destination Host.
        if (mode == 1 &&
            (hostId < 0 || hostId >= numONUs))
        {
            delete msg;
            throw cRuntimeError(
                "Invalid Host ONU ID in Local Sharing grant"
            );
        }

        if (lsDuration < 0)
        {
            delete msg;
            throw cRuntimeError(
                "Invalid Local Sharing duration"
            );
        }

        if (grantActive || waitingToSendReport || deferredGrant != nullptr)
        {
            long long onuId =
                (long long)par("onuId").intValue();

            delete msg;

            throw cRuntimeError(
                "ONU %lld received an overlapping GATE while another grant/REPORT was active",
                onuId
            );
        }

        // The Host REPORT has already been sent, so the ONU may accept a new
        // GATE immediately. However, the previous Mode 2 transaction still
        // has to drain DataBuffers and transmit the previous grant's own DATA.
        // Defer execution of the new GATE so it cannot overwrite that state.
        if (hostPostReportActive)
        {
            const double delaySeconds =
                msg->par("delay_after_rec_grant").doubleValue();

            const SimTime requestedReadyAt =
                simTime() + SimTime(delaySeconds, SIMTIME_S);

            msg->addPar("deferredReadyAt");
            msg->par("deferredReadyAt").setDoubleValue(
                requestedReadyAt.dbl()
            );

            // The GATE will be scheduled at deferredReadyAt later. Avoid
            // applying delay_after_rec_grant a second time when it resumes.
            msg->par("delay_after_rec_grant").setDoubleValue(0.0);

            deferredGrant = msg;

            EV_INFO << "ONU " << par("onuId").intValue()
                    << " accepted a new GATE while finishing previous Host work"
                    << " | New GATE will be processed at/after "
                    << requestedReadyAt
                    << " | Previous grant remaining = "
                    << grantBitsRemaining << " bits"
                    << endl;
            return;
        }

        // A scheduled Transmit event is expected for an active grant. The
        // grantActive/waitingToSendReport checks above protect normal overlap.
        long grantBytes =
            msg->par("grantBytes").longValue();

        double delaySeconds =
            msg->par("delay_after_rec_grant").doubleValue();

        if (grantBytes < 0 || delaySeconds < 0)
        {
            delete msg;
            throw cRuntimeError("Invalid GATE parameters");
        }

        grantMode = mode;
        hostReportSentBeforeData = false;

        //If packet is being sent to other ONU DelayExperiencedByPacket comes into picture
        if(grantMode==1)
        {
            DelayExperiencedByPacket = SimTime(msg->par("DelayExperiencedByPacket").doubleValue(),SIMTIME_S);
        }


        // The Host ID is relevant to this grant only in Mode 1.
        grantHostId = (mode == 1) ? hostId : -1;
        grantBitsRemaining = grantBytes * 8;
        grantActive = true;

        // Mode 2 ONU acts as the Host and drains its LS buffer first.
        sendingLocalSharingBuffer = (mode == 2);

        EV_INFO << "\nONU " << par("onuId").intValue()
                << " accepted GATE"
                << "\nMode = " << grantMode
                << "\nGrant Host ID = " << grantHostId
                << "\nGrant = " << grantBytes << " bytes"
                << "\nLS duration = "
                << lsDuration * 1e6 << " us"
                << "\nWait after GATE reception = "
                << delaySeconds * 1e6 << " us"
                << endl;

        delete msg;

        scheduleAt(
            simTime() + SimTime(delaySeconds, SIMTIME_S),
            transmitMsg
        );

        return;
    }


    // ========================================
    // DATA AND REPORT TRANSMISSION
    // ========================================

    if (msg == transmitMsg)
    {
        // ------------------------------------
        // REPORT transmission
        // ------------------------------------

        if (waitingToSendReport)
        {
            EV_INFO << "ONU " << par("onuId").intValue()
                    << " sending REPORT"
                    << " | Mode = " << grantMode
                    << endl;

            // Start timing at the actual REPORT send event, after serialization.
            currentReportTxStart = simTime();
            currentReportedBytes =
                pendingReport->par("queueBytes").longValue();
            awaitingGateForReport = true;

            if (grantMode == 1)
            {
                // Assign the Host to this REPORT at transmission time.
                pendingReport->par("hostId").setLongValue(
                    grantHostId
                );
                pendingReport->setKind(1);
                send(pendingReport, "lsOut");
            }
            else
            {
                // Normal ONU or Host's own REPORT.
                // Leave hostId unchanged.
                pendingReport->setKind(2);
                send(pendingReport, "out");
            }

            pendingReport = nullptr;
            waitingToSendReport = false;

            if (grantMode == 2 && hostReportSentBeforeData)
            {
                // The Host's REPORT has reached the upstream path. Release
                // grantActive so a newly arriving GATE can be accepted, while
                // retaining the previous Mode 2 state and grant allowance.
                hostPostReportActive = true;
                grantActive = false;

                // Continue the previous Host transaction using its preserved
                // grantBitsRemaining, grantMode, and Local Sharing buffers.
                scheduleAt(simTime(), transmitMsg);
            }
            else
            {
                // Modes 0 and 1 complete after their DATA-then-REPORT flow.
                grantActive = false;
                grantBitsRemaining = 0;
                sendingLocalSharingBuffer = false;
                grantHostId = -1;
                grantMode = 0;
            }

            return;
        }


        // ------------------------------------
        // Mode 2: REPORTs, Host REPORT, then LS DATA
        // ------------------------------------

        if (grantMode == 2 && sendingLocalSharingBuffer)
        {
            // 1. Forward every collected REPORT first.
            if (!ReportBuffers.empty())
            {
                transmitNextLocalSharingPacket();
                return;
            }

            // 2. Once collected REPORTs are forwarded, send the Host's own
            // REPORT before any collected DATA is drained.
            if (!hostReportSentBeforeData)
            {
                dropExpiredOwnPackets();

                // The Host's grant is exclusively for its own DATA.
                // Locally shared DATA is forwarded separately and must not
                // reduce the Host's available grant allowance.
                const long sendableBytes =
                    calculateSendableOwnBytes(grantBitsRemaining);
                const long currentQueueBytes = getQueuedBytes();
                const long remainingQueueBytes =
                    std::max(0L, currentQueueBytes - sendableBytes);

                hostReportSentBeforeData = true;

                EV_INFO << "Host ONU " << par("onuId").intValue()
                        << " preparing REPORT after collected REPORTs"
                        << " | Current own queue = " << currentQueueBytes
                        << " bytes"
                        << " | Host own-DATA grant = " << grantBitsRemaining
                        << " bits"
                        << " | Own DATA sendable = " << sendableBytes
                        << " bytes"
                        << " | Queue reported to OLT = "
                        << remainingQueueBytes << " bytes"
                        << endl;

                prepareReport(remainingQueueBytes);
                return;
            }

            // 3. After the Host REPORT has been sent, drain every collected
            // DATA packet independently of the Host's own grant allowance.
            if (!DataBuffers.empty())
            {
                transmitNextLocalSharingPacket();
                return;
            }

            sendingLocalSharingBuffer = false;
            EV_INFO << "Host ONU " << par("onuId").intValue()
                    << " finished draining Local Sharing DATA"
                    << " | Remaining grant = " << grantBitsRemaining
                    << " bits"
                    << endl;
        }


        // ------------------------------------
        // Transmit this ONU's own DATA
        // ------------------------------------

        // Drop packets whose delay budgets have expired before calculating
        // the Host's REPORT.
        if (grantMode == 1)
        {
            while (!queue.empty())
            {
                cPacket *packet = queue.front();
                const SimTime packetAge =
                    simTime() - packet->getCreationTime();

                const SimTime allowedDelay =
                    PDB - DelayExperiencedByPacket - rnToONUDelay;

                if (packetAge <= allowedDelay)
                    break;

                queue.pop();
                packetsDropped++;
                delete packet;
            }
        }
        else
        {
            dropExpiredOwnPackets();
        }

        if (grantActive && !queue.empty())
        {
            cPacket *packet = queue.front();
            long packetBits = packet->getBitLength();

            if (packetBits <= grantBitsRemaining)
            {
                queue.pop();
                grantBitsRemaining -= packetBits;

                SimTime txTime(
                    packetBits /
                    par("dataRate").doubleValue(),
                    SIMTIME_S
                );

                EV_INFO << "ONU " << par("onuId").intValue()
                        << " transmitting own DATA"
                        << " | Source ONU = "
                        << packet->par("onuId").longValue()
                        << " | Packet hostId before transmission = "
                        << packet->par("hostId").longValue()
                        << " | Bits = " << packetBits
                        << " | Grant remaining = "
                        << grantBitsRemaining
                        << " bits"
                        << " | Queue packets = " << queue.size()
                        << " | Mode = " << grantMode
                        << endl;

                if (grantMode == 1)
                {
                    // Set the packet's intended Host at transmission time.
                    packet->par("hostId").setLongValue(
                        grantHostId
                    );
                    packet->setKind(1);
                    send(packet, "lsOut");
                }
                else
                {
                    
                    // Modes 0 and 2 do not change packet hostId.
                    packet->setKind(2);
                    send(packet, "out");
                }

                scheduleAt(simTime() + txTime, transmitMsg);
                return;
            }
        }


        // ------------------------------------
        // Own DATA burst finished.
        // Prepare the separate REPORT.
        // ------------------------------------

        EV_INFO << "ONU " << par("onuId").intValue()
                << " own DATA burst finished"
                << " | Queue packets = " << queue.size()
                << " | Mode = " << grantMode
                << endl;

        if (grantMode == 2 && hostReportSentBeforeData)
        {
            // The Host REPORT was already sent before this DATA burst.
            grantActive = false;
            grantBitsRemaining = 0;
            sendingLocalSharingBuffer = false;
            grantHostId = -1;
            grantMode = 0;
            hostReportSentBeforeData = false;
            hostPostReportActive = false;

            // The old Host transaction is now completely finished. A GATE
            // received after the Host REPORT can safely begin now, subject
            // to its original delay_after_rec_grant.
            resumeDeferredGrant();
        }
        else
        {
            // Preserve the original DATA-then-REPORT behavior for Modes 0/1.
            prepareReport();
        }

        return;
    }


    // ========================================
    // UNEXPECTED MESSAGE
    // ========================================

    delete msg;
}


void ONU::finish()
{
    cancelAndDelete(generateMsg);
    cancelAndDelete(transmitMsg);
    cancelAndDelete(trafficStateMsg);

    if (pendingReport != nullptr)
    {
        delete pendingReport;
        pendingReport = nullptr;
    }

    if (deferredGrant != nullptr)
    {
        if (deferredGrant->isScheduled())
            cancelEvent(deferredGrant);
        delete deferredGrant;
        deferredGrant = nullptr;
    }

    while (!queue.empty())
    {
        delete queue.front();
        queue.pop();
    }

    while (!ReportBuffers.empty())
    {
        delete ReportBuffers.front();
        ReportBuffers.pop();
    }

    while (!DataBuffers.empty())
    {
        delete DataBuffers.front();
        DataBuffers.pop();
    }
    recordScalar("Packets Created", packetsCreated);
    recordScalar("Packets Dropped", packetsDropped);

    if (reportTurnaroundFile.is_open())
        reportTurnaroundFile.close();
}
